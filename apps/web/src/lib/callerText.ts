// Caller page text in the caller's phone language (English, Spanish, Arabic). The agent itself
// switches language on its own; this keeps the buttons and labels in the same language.
export type Lang = "en" | "es" | "ar";

/** The phone's language, or ?lang=es / ?lang=ar on the link (handy for a demo). */
export function phoneLang(): Lang {
  const forced = typeof location !== "undefined" ? new URLSearchParams(location.search).get("lang") : null;
  const l = (forced ?? (typeof navigator !== "undefined" ? navigator.language : "en")).slice(0, 2).toLowerCase();
  return l === "es" || l === "ar" ? l : "en";
}

